-- Parameters: :start_date (first day of month), :end_date (last day of month)
WITH
dateParams (START_DATE, END_DATE) AS (
  VALUES (
    CAST(:start_date AS DATE),
    CAST(:end_date AS DATE)
  )
),
ActiveBeforeStartDate AS (
    SELECT DISTINCT
    A.PRIMARY_PERSON_SERIAL AS PERSON_SERIAL
    FROM
        CORE.ACCOUNT A
        CROSS JOIN dateParams
        JOIN CORE.SHARE S
        ON A.SERIAL = S.PARENT_SERIAL
        AND S.ID = '0001'
        AND S.OPEN_DATE  < dateParams.START_DATE
        AND (S.CLOSE_DATE      IS NULL OR S.CLOSE_DATE      > dateParams.START_DATE)
        AND (S.CHARGE_OFF_DATE IS NULL OR S.CHARGE_OFF_DATE > dateParams.START_DATE)
),
newOpenedAccounts AS (
    SELECT  -- Use this CTE to get all currently active members who opened acct in time range specified
    PERSON.SERIAL AS PERSON_SERIAL,
    YEAR(MAX(ENV.POSTING_DATE)) - YEAR(MIN(ACCOUNT.OPEN_DATE)) -
            CASE
                WHEN (MONTH(MAX(ACCOUNT.CLOSE_DATE)) * 100 + DAY(MAX(ACCOUNT.CLOSE_DATE))) < (MONTH(MIN(ACCOUNT.OPEN_DATE)) * 100 + DAY(MIN(ACCOUNT.OPEN_DATE))) THEN 1
                ELSE 0
            END AS MEMBERSHIP_DURATION_YRS
    FROM
        CORE.ENV AS ENV CROSS JOIN
        dateParams CROSS JOIN
        CORE.PERSON AS PERSON
        JOIN CORE.ACCOUNT AS ACCOUNT ON PERSON.SERIAL = ACCOUNT.PRIMARY_PERSON_SERIAL -- must be a primary person on at least one account
            AND ACCOUNT.CLOSE_DATE IS NULL -- only active accounts
        JOIN CORE.SHARE AS SHARE ON ACCOUNT.SERIAL = SHARE.PARENT_SERIAL
        LEFT JOIN CORE.PERSON_TYPE AS PERSON_TYPE ON PERSON.TYPE_SERIAL = PERSON_TYPE.SERIAL
    WHERE
        (PERSON_TYPE.DESCRIPTION IS NULL OR PERSON_TYPE.DESCRIPTION != 'Vendor') -- Is not a vendor
    GROUP BY
        PERSON.SERIAL
    HAVING
        MIN(ACCOUNT.OPEN_DATE) BETWEEN MAX(START_DATE) AND MAX(END_DATE))
SELECT -- use this to get accounts that were opened before the time range specified for those returning members
    PERSON.SERIAL AS PERSON_SERIAL,
    MAX( PERSON.LAST_NAME || COALESCE(', ' ||  PERSON.FIRST_NAME, '')) as PERSON_NAME,
    MAX(CASE
        WHEN ActiveBeforeStartDate.PERSON_SERIAL IS NULL THEN 'NO'
        ELSE 'YES'
    END) AS ACTIVE_BEFORE_START_DATE,
    MAX(ACCOUNT_ELIGIBILITY.DESCRIPTION) AS AGENCY,
    MAX(ACCOUNT_TYPE.DESCRIPTION) AS CATEGORY,
    listagg(
            CASE
            WHEN ACCOUNT.OPEN_DATE >= (SELECT START_DATE FROM dateParams)
            THEN ACCOUNT.ACCOUNT_NUMBER || ': ' || ACCOUNT.OPEN_DATE END, ', ') AS ACCOUNTS_OPENED,
    CASE WHEN MIN(ACCOUNT.OPEN_DATE) < MAX(START_DATE) THEN 'YES' ELSE 'NO' END AS RETURNING_MEMBER,
    MIN(ACCOUNT.OPEN_DATE) AS FIRST_ACCT_OPEN_DATE,
    MAX(ACCOUNT.CLOSE_DATE) AS LATEST_ACCT_CLOSE_DATE
FROM
    dateParams
    CROSS JOIN newOpenedAccounts
    JOIN CORE.PERSON AS PERSON ON newOpenedAccounts.PERSON_SERIAL = PERSON.SERIAL
    JOIN CORE.ACCOUNT AS ACCOUNT ON PERSON.SERIAL = ACCOUNT.PRIMARY_PERSON_SERIAL
    JOIN CORE.ACCOUNT_TYPE AS ACCOUNT_TYPE ON ACCOUNT.TYPE_SERIAL = ACCOUNT_TYPE.SERIAL
    JOIN CORE.ACCOUNT_ELIGIBILITY AS ACCOUNT_ELIGIBILITY ON ACCOUNT.ELIGIBILITY_SERIAL = ACCOUNT_ELIGIBILITY.SERIAL
    LEFT JOIN ActiveBeforeStartDate ON ActiveBeforeStartDate.PERSON_SERIAL = PERSON.SERIAL
WHERE
    ActiveBeforeStartDate.PERSON_SERIAL IS NULL
GROUP BY
    PERSON.SERIAL

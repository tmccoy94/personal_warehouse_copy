SELECT
    ACCOUNT.SERIAL                      AS account_serial,
    ACCOUNT.PRIMARY_PERSON_SERIAL       AS primary_person_serial,
    ACCOUNT.OPEN_DATE                   AS open_date,
    ACCOUNT.CLOSE_DATE                  AS close_date,
    ACCOUNT.DORMANCY_RESTRICTION        AS dormancy_restriction,
    ACCOUNT.RELATIONSHIP_SERIAL         AS relationship_serial,
    ACCOUNT.ELIGIBILITY_SERIAL          AS eligibility_serial,
    ACCOUNT.TYPE_SERIAL                 AS type_serial,
    ACCOUNT_ELIGIBILITY.DESCRIPTION     AS eligibility_description,
    ACCOUNT_TYPE.DESCRIPTION            AS type_description,
    ACCOUNT_RELATIONSHIP.DESCRIPTION    AS relationship_description,
    ACCOUNT_CLOSE_REASON.DESCRIPTION    AS close_reason_description
FROM
    CORE.ACCOUNT                AS ACCOUNT LEFT JOIN
    CORE.ACCOUNT_ELIGIBILITY    AS ACCOUNT_ELIGIBILITY   ON ACCOUNT_ELIGIBILITY.SERIAL   = ACCOUNT.ELIGIBILITY_SERIAL LEFT JOIN
    CORE.ACCOUNT_TYPE           AS ACCOUNT_TYPE          ON ACCOUNT_TYPE.SERIAL          = ACCOUNT.TYPE_SERIAL LEFT JOIN
    CORE.ACCOUNT_RELATIONSHIP   AS ACCOUNT_RELATIONSHIP  ON ACCOUNT_RELATIONSHIP.SERIAL  = ACCOUNT.RELATIONSHIP_SERIAL LEFT JOIN
    CORE.ACCOUNT_CLOSE_REASON   AS ACCOUNT_CLOSE_REASON  ON ACCOUNT_CLOSE_REASON.SERIAL  = ACCOUNT.CLOSE_REASON_SERIAL

-- Parameters: :start_date (first day of month), :end_date (last day of month)
WITH
dateParams (START_DATE, END_DATE) AS (
  VALUES (
    CAST(:start_date AS DATE),
    CAST(:end_date AS DATE)
  )
),
ActiveOnStartDate AS (
  SELECT DISTINCT
    A.PRIMARY_PERSON_SERIAL AS PERSON_SERIAL
  FROM
      CORE.ACCOUNT A CROSS JOIN dateParams
  JOIN CORE.SHARE S
    ON A.SERIAL = S.PARENT_SERIAL
   AND S.ID = '0001'
   AND S.OPEN_DATE  <= dateParams.START_DATE
   AND (S.CLOSE_DATE      IS NULL OR S.CLOSE_DATE      > dateParams.START_DATE)
   AND (S.CHARGE_OFF_DATE IS NULL OR S.CHARGE_OFF_DATE > dateParams.START_DATE)
),
closedGeneralShares  AS (SELECT
    PERSON.SERIAL AS PERSON_SERIAL,
    SHARE.OPEN_DATE AS SHARE_OPEN_DATE,
    SHARE.CLOSE_DATE AS SHARE_CLOSE_DATE
FROM
    CORE.ENV AS ENV CROSS JOIN
    dateParams CROSS JOIN
    CORE.PERSON AS PERSON
    JOIN CORE.ACCOUNT AS ACCOUNT ON PERSON.SERIAL = ACCOUNT.PRIMARY_PERSON_SERIAL
    JOIN CORE.SHARE AS SHARE ON ACCOUNT.SERIAL = SHARE.PARENT_SERIAL
        AND SHARE.ID = '0001' AND SHARE.CLOSE_DATE IS NOT NULL
    LEFT JOIN CORE.PERSON_TYPE AS PERSON_TYPE ON PERSON.TYPE_SERIAL = PERSON_TYPE.SERIAL
WHERE
    (PERSON_TYPE.DESCRIPTION IS NULL OR PERSON_TYPE.DESCRIPTION != 'Vendor') AND
    SHARE.CLOSE_DATE BETWEEN START_DATE AND END_DATE
ORDER BY
    PERSON.SERIAL, SHARE.CLOSE_DATE DESC)

SELECT
    PERSON.SERIAL AS PERSON_SERIAL,
    MAX( PERSON.LAST_NAME || ', ' || COALESCE( PERSON.FIRST_NAME, '')) as PERSON_NAME,
    MAX(CASE
        WHEN ActiveOnStartDate.PERSON_SERIAL IS NULL THEN 'NO'
        ELSE 'YES'
    END) AS ACTIVE_ON_START_DATE,
    LISTAGG(ACCOUNT.ACCOUNT_NUMBER || COALESCE(' (CLOSED ' || ACCOUNT.CLOSE_DATE || ')', ' (STILL OPEN)') || ': ' || COALESCE(UPPER(ACCOUNT_CLOSE_REASON.DESCRIPTION), 'NONE GIVEN'), ', ') WITHIN GROUP ( ORDER BY ACCOUNT.CLOSE_DATE DESC) AS AC_CLOSE_REASON,
    MIN(CASE WHEN SHARE.ID = '0001' THEN SHARE.OPEN_DATE END) AS FIRST_GENSH_OPENED,
    MAX(CASE WHEN SHARE.ID = '0001' THEN SHARE.CLOSE_DATE END) AS LAST_GENSH_CLOSED,
    LISTAGG(CASE WHEN SHARE.ID = '0001' THEN SHARE.ID || ': ' || SHARE.CLOSE_DATE END, ', ') WITHIN GROUP ( ORDER BY SHARE.CLOSE_DATE DESC ) SHARES_CLOSED,
    YEAR(MAX(CASE WHEN SHARE.ID = '0001' THEN SHARE.CLOSE_DATE END)) - YEAR(MIN(CASE WHEN SHARE.ID = '0001' THEN SHARE.OPEN_DATE END)) -
            CASE
                WHEN (MONTH(MAX(CASE WHEN SHARE.ID = '0001' THEN SHARE.CLOSE_DATE END)) * 100 + DAY(MAX(CASE WHEN SHARE.ID = '0001' THEN SHARE.CLOSE_DATE END))) < (MONTH(MIN(ACCOUNT.OPEN_DATE)) * 100 + DAY(MIN(ACCOUNT.OPEN_DATE))) THEN 1
                ELSE 0
            END AS MEMBERSHIP_DURATION
FROM
    CORE.ENV AS ENV CROSS JOIN
    CORE.PERSON AS PERSON
    JOIN closedGeneralShares ON closedGeneralShares.PERSON_SERIAL = PERSON.SERIAL
    JOIN CORE.ACCOUNT AS ACCOUNT ON PERSON.SERIAL = ACCOUNT.PRIMARY_PERSON_SERIAL
    JOIN CORE.SHARE AS SHARE ON ACCOUNT.SERIAL = SHARE.PARENT_SERIAL
        AND SHARE.ID = '0001'
    LEFT JOIN CORE.PERSON_TYPE AS PERSON_TYPE ON PERSON.TYPE_SERIAL = PERSON_TYPE.SERIAL
    LEFT JOIN CORE.AC_NOTE AS AC_NOTE ON ACCOUNT.SERIAL = AC_NOTE.PARENT_SERIAL
        AND (AC_NOTE.EXPIRATION_DATE IS NULL OR
            AC_NOTE.EXPIRATION_DATE > ENV.POSTING_DATE)
    LEFT JOIN CORE.NOTE_TYPE AS NOTE_TYPE ON AC_NOTE.TYPE_SERIAL = NOTE_TYPE.SERIAL
    LEFT JOIN CORE.ACCOUNT_CLOSE_REASON AS ACCOUNT_CLOSE_REASON ON ACCOUNT_CLOSE_REASON.SERIAL = ACCOUNT.CLOSE_REASON_SERIAL
    LEFT JOIN ActiveOnStartDate ON ActiveOnStartDate.PERSON_SERIAL = PERSON.SERIAL
WHERE
    (PERSON_TYPE.DESCRIPTION IS NULL OR PERSON_TYPE.DESCRIPTION != 'Vendor')
GROUP BY
    PERSON.SERIAL
HAVING
    COUNT(CASE WHEN SHARE.CLOSE_DATE IS NULL AND SHARE.ID = '0001' THEN SHARE.SERIAL END) = 0
;

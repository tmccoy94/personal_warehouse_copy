-- Show the same shares directly from DB2
SELECT
    SHARE.SERIAL AS share_serial,
    ACCOUNT.PRIMARY_PERSON_SERIAL AS person_serial,
    SHARE.ID AS share_id,
    SHARE.OPEN_DATE AS open_date,
    SHARE.CLOSE_DATE AS close_date,
    SHARE.CHARGE_OFF_DATE AS charge_off_date
FROM CORE.SHARE AS SHARE
JOIN CORE.ACCOUNT AS ACCOUNT ON ACCOUNT.SERIAL = SHARE.PARENT_SERIAL
WHERE ACCOUNT.PRIMARY_PERSON_SERIAL IN (5945, 10782, 14928, 27496, 29851, 30969, 31413, 34622, 49142, 138648)
  AND SHARE.ID = '0001'
ORDER BY ACCOUNT.PRIMARY_PERSON_SERIAL

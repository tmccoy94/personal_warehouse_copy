-- DB2: Count members with each individual service
SELECT 'Open Shares (any type)' AS service, COUNT(DISTINCT P.SERIAL) AS member_count
FROM CORE.PERSON P
WHERE EXISTS (
    SELECT 1 FROM CORE.ACCOUNT A INNER JOIN CORE.SHARE S ON A.SERIAL = S.PARENT_SERIAL
    WHERE A.PRIMARY_PERSON_SERIAL = P.SERIAL AND S.CLOSE_DATE IS NULL AND S.CHARGE_OFF_DATE IS NULL
)
UNION ALL
SELECT 'Open Loans (any type)', COUNT(DISTINCT P.SERIAL)
FROM CORE.PERSON P
WHERE EXISTS (
    SELECT 1 FROM CORE.ACCOUNT A INNER JOIN CORE.LOAN L ON A.SERIAL = L.PARENT_SERIAL
    WHERE A.PRIMARY_PERSON_SERIAL = P.SERIAL AND L.CLOSE_DATE IS NULL AND L.CHARGE_OFF_DATE IS NULL
)
UNION ALL
SELECT 'Online Banking (Access_Softek)', COUNT(DISTINCT P.SERIAL)
FROM CORE.PERSON P
WHERE EXISTS (
    SELECT 1 FROM CORE.LOGIN LG INNER JOIN CORE.LOGIN_CHANNEL LC ON LG.CHANNEL_SERIAL = LC.SERIAL
    WHERE LG.PERSON_SERIAL = P.SERIAL AND LC.DESCRIPTION = 'Access_Softek'
)
UNION ALL
SELECT 'Direct Deposit (ACH >= 500, last 30 days)', COUNT(DISTINCT P.SERIAL)
FROM CORE.PERSON P CROSS JOIN CORE.ENV ENV
WHERE EXISTS (
    SELECT 1 FROM CORE.ACCOUNT A INNER JOIN CORE.SHARE S ON A.SERIAL = S.PARENT_SERIAL
    WHERE A.PRIMARY_PERSON_SERIAL = P.SERIAL
      AND S.CLOSE_DATE IS NULL AND S.CHARGE_OFF_DATE IS NULL
      AND S.ACH_DEPOSIT_LAST_AMOUNT >= 500.00
      AND S.ACH_DEPOSIT_LAST_DATE > ENV.POSTING_DATE - 30 DAYS
)
UNION ALL
SELECT 'Bill Payment (SOURCE=B, last 30 days)', COUNT(DISTINCT P.SERIAL)
FROM CORE.PERSON P CROSS JOIN CORE.ENV ENV
WHERE EXISTS (
    SELECT 1 FROM CORE.TRANSACTION T INNER JOIN CORE.MONETARY M ON T.SERIAL = M.PARENT_SERIAL
    WHERE T.PERSON_SERIAL = P.SERIAL
      AND M.SOURCE = 'B'
      AND T.POSTING_DATE > ENV.POSTING_DATE - 30 DAYS
)

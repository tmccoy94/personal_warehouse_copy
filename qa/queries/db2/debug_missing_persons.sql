-- Check the 10 missing persons directly in DB2
SELECT
    PERSON.SERIAL AS person_serial,
    PERSON_TYPE.DESCRIPTION AS person_type,
    SUM(CASE WHEN SHARE.ID = '0001' THEN 1 ELSE 0 END) AS total_0001_shares,
    SUM(CASE WHEN SHARE.ID = '0001' AND SHARE.CLOSE_DATE IS NULL AND SHARE.CHARGE_OFF_DATE IS NULL THEN 1 ELSE 0 END) AS open_0001_shares,
    MAX(ACCOUNT.CLOSE_DATE) AS latest_account_close_date
FROM CORE.PERSON AS PERSON
LEFT JOIN CORE.PERSON_TYPE AS PERSON_TYPE ON PERSON_TYPE.SERIAL = PERSON.TYPE_SERIAL
LEFT JOIN CORE.ACCOUNT AS ACCOUNT ON ACCOUNT.PRIMARY_PERSON_SERIAL = PERSON.SERIAL
LEFT JOIN CORE.SHARE AS SHARE ON SHARE.PARENT_SERIAL = ACCOUNT.SERIAL AND SHARE.ID = '0001'
WHERE PERSON.SERIAL IN (10782, 31413, 34622, 49142, 5945, 14928, 27496, 29851, 30969, 138648)
GROUP BY PERSON.SERIAL, PERSON_TYPE.DESCRIPTION
ORDER BY PERSON.SERIAL

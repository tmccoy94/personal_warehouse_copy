-- DB2: Members added in Feb 2026 (new members, not returning)
-- Matches members_added.sql pipeline query logic exactly.
-- Uses 2026-02-01 to 2026-02-28 — hardcoded for D0001T32 (May 2026 snapshot).
WITH dateParams(START_DATE, END_DATE) AS (
    VALUES (CAST('2026-02-01' AS DATE), CAST('2026-02-28' AS DATE))
),
ActiveBeforeStartDate AS (
    SELECT DISTINCT A.PRIMARY_PERSON_SERIAL AS PERSON_SERIAL
    FROM CORE.ACCOUNT AS A CROSS JOIN dateParams
    JOIN CORE.SHARE AS S ON A.SERIAL = S.PARENT_SERIAL
      AND S.ID              = '0001'
      AND S.OPEN_DATE        < dateParams.START_DATE
      AND (S.CLOSE_DATE      IS NULL OR S.CLOSE_DATE      > dateParams.START_DATE)
      AND (S.CHARGE_OFF_DATE IS NULL OR S.CHARGE_OFF_DATE > dateParams.START_DATE)
),
newOpenedAccounts AS (
    SELECT PERSON.SERIAL AS PERSON_SERIAL
    FROM dateParams CROSS JOIN
         CORE.PERSON  AS PERSON
         JOIN CORE.ACCOUNT AS ACCOUNT ON PERSON.SERIAL = ACCOUNT.PRIMARY_PERSON_SERIAL
              AND ACCOUNT.CLOSE_DATE IS NULL
         JOIN CORE.SHARE AS SHARE ON ACCOUNT.SERIAL = SHARE.PARENT_SERIAL
         LEFT JOIN CORE.PERSON_TYPE AS PERSON_TYPE ON PERSON.TYPE_SERIAL = PERSON_TYPE.SERIAL
    WHERE (PERSON_TYPE.DESCRIPTION IS NULL OR PERSON_TYPE.DESCRIPTION != 'Vendor')
    GROUP BY PERSON.SERIAL
    HAVING MIN(ACCOUNT.OPEN_DATE) BETWEEN MAX(START_DATE) AND MAX(END_DATE)
)
SELECT COUNT(*) AS members_added
FROM newOpenedAccounts AS nm
WHERE NOT EXISTS (
    SELECT 1 FROM ActiveBeforeStartDate AS ab
    WHERE ab.PERSON_SERIAL = nm.PERSON_SERIAL
)

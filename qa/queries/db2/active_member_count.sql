-- DB2: Active Member Count (3+ services)
-- Source: Active Member Count.sql — "Get total member count only"
-- Using COUNT(DISTINCT PERSON.SERIAL) to match warehouse person_serial comparison
WITH ProductCounts(personSerial, cnt) AS (
    SELECT PERSON_SERIAL, COUNT(PRODUCT) AS PROD_COUNT
    FROM (
        -- 1. Open shares by type
        SELECT PERSON.SERIAL AS PERSON_SERIAL, SH_TYPE.DESCRIPTION AS PRODUCT
        FROM CORE.ENV AS ENV CROSS JOIN
             CORE.ACCOUNT AS ACCOUNT
                 INNER JOIN CORE.SHARE   AS SHARE   ON ACCOUNT.SERIAL = SHARE.PARENT_SERIAL
                 INNER JOIN CORE.SH_TYPE AS SH_TYPE ON SHARE.TYPE_SERIAL = SH_TYPE.SERIAL
                 INNER JOIN CORE.PERSON  AS PERSON  ON ACCOUNT.PRIMARY_PERSON_SERIAL = PERSON.SERIAL
        WHERE SHARE.CLOSE_DATE IS NULL AND SHARE.CHARGE_OFF_DATE IS NULL

        UNION ALL

        -- 2. Open loans by type
        SELECT PERSON.SERIAL AS PERSON_SERIAL, LN_TYPE.DESCRIPTION AS PRODUCT
        FROM CORE.ENV AS ENV CROSS JOIN
             CORE.ACCOUNT AS ACCOUNT
                 INNER JOIN CORE.LOAN    AS LOAN    ON ACCOUNT.SERIAL = LOAN.PARENT_SERIAL
                 INNER JOIN CORE.LN_TYPE AS LN_TYPE ON LOAN.TYPE_SERIAL = LN_TYPE.SERIAL
                 INNER JOIN CORE.PERSON  AS PERSON  ON ACCOUNT.PRIMARY_PERSON_SERIAL = PERSON.SERIAL
        WHERE LOAN.CLOSE_DATE IS NULL AND LOAN.CHARGE_OFF_DATE IS NULL

        UNION ALL

        -- 3. Online banking (Access_Softek only)
        SELECT DISTINCT PERSON.SERIAL AS PERSON_SERIAL,
               CASE WHEN LOGIN_CHANNEL.DESCRIPTION = 'Access_Softek' THEN 'Online Banking' END AS PRODUCT
        FROM CORE.ACCOUNT AS ACCOUNT
                 INNER JOIN CORE.PERSON       AS PERSON       ON ACCOUNT.PRIMARY_PERSON_SERIAL = PERSON.SERIAL
                 LEFT  JOIN CORE.LOGIN        AS LOGIN        ON PERSON.SERIAL = LOGIN.PERSON_SERIAL
                 LEFT  JOIN CORE.LOGIN_CHANNEL AS LOGIN_CHANNEL ON LOGIN.CHANNEL_SERIAL = LOGIN_CHANNEL.SERIAL
        WHERE LOGIN_CHANNEL.DESCRIPTION = 'Access_Softek'

        UNION ALL

        -- 4. Bill payment — MONETARY.SOURCE = 'B' within last 30 days
        SELECT PERSON.SERIAL AS PERSON_SERIAL,
               CASE WHEN MONETARY.SOURCE = 'B' AND TRANSACTION.POSTING_DATE > ENV.POSTING_DATE - 30 DAYS
                    THEN 'Bill Payment' END AS PRODUCT
        FROM CORE.ENV AS ENV CROSS JOIN
             CORE.ACCOUNT AS ACCOUNT
                 INNER JOIN CORE.PERSON      AS PERSON      ON ACCOUNT.PRIMARY_PERSON_SERIAL = PERSON.SERIAL
                 INNER JOIN CORE.TRANSACTION AS TRANSACTION ON PERSON.SERIAL = TRANSACTION.PERSON_SERIAL
                 LEFT  JOIN CORE.MONETARY    AS MONETARY    ON TRANSACTION.SERIAL = MONETARY.PARENT_SERIAL
        WHERE MONETARY.SOURCE = 'B' AND TRANSACTION.POSTING_DATE > ENV.POSTING_DATE - 30 DAYS

        UNION ALL

        -- 5. Direct deposit — ACH >= $500 within last 30 days (from SHARE table)
        SELECT PERSON.SERIAL AS PERSON_SERIAL,
               CASE WHEN SHARE.ACH_DEPOSIT_LAST_AMOUNT >= 500.00
                     AND SHARE.ACH_DEPOSIT_LAST_DATE > ENV.POSTING_DATE - 30 DAYS
                    THEN 'Direct Deposit' END AS PRODUCT
        FROM CORE.ENV AS ENV CROSS JOIN
             CORE.ACCOUNT AS ACCOUNT
                 INNER JOIN CORE.PERSON AS PERSON ON ACCOUNT.PRIMARY_PERSON_SERIAL = PERSON.SERIAL
                 INNER JOIN CORE.SHARE  AS SHARE  ON ACCOUNT.SERIAL = SHARE.PARENT_SERIAL
        WHERE SHARE.CLOSE_DATE IS NULL
          AND SHARE.CHARGE_OFF_DATE IS NULL
          AND SHARE.ACH_DEPOSIT_LAST_AMOUNT >= 500.00
          AND SHARE.ACH_DEPOSIT_LAST_DATE > ENV.POSTING_DATE - 30 DAYS
    )
    GROUP BY PERSON_SERIAL
)
SELECT COUNT(DISTINCT PERSON.SERIAL) AS active_member_count
FROM CORE.ACCOUNT AS ACCOUNT
         INNER JOIN CORE.SHARE   AS SHARE   ON ACCOUNT.SERIAL = SHARE.PARENT_SERIAL
         INNER JOIN CORE.PERSON  AS PERSON  ON ACCOUNT.PRIMARY_PERSON_SERIAL = PERSON.SERIAL
         LEFT  JOIN CORE.PERSON_TYPE AS PERSON_TYPE ON PERSON.TYPE_SERIAL = PERSON_TYPE.SERIAL
         INNER JOIN ProductCounts   ON PERSON.SERIAL = ProductCounts.personSerial
WHERE SHARE.ID         = '0001'
  AND SHARE.CLOSE_DATE IS NULL
  AND SHARE.CHARGE_OFF_DATE IS NULL
  AND ProductCounts.cnt >= 3
  AND NOT EXISTS (
      SELECT 1 FROM CORE.PERSON_TYPE AS PT
                        INNER JOIN CORE.PERSON AS P2 ON PT.SERIAL = P2.TYPE_SERIAL
      WHERE PERSON.SERIAL = P2.SERIAL AND PT.DESCRIPTION = 'Vendor'
  )
  AND NOT EXISTS (
      SELECT 1 FROM CORE.NOTE_TYPE AS NOTE_TYPE
                        INNER JOIN CORE.AC_NOTE AS AC_NOTE ON NOTE_TYPE.SERIAL = AC_NOTE.TYPE_SERIAL
                        INNER JOIN CORE.ACCOUNT AS ACCT    ON AC_NOTE.PARENT_SERIAL = ACCT.SERIAL
                        CROSS JOIN CORE.ENV AS ENV
      WHERE ACCT.PRIMARY_PERSON_SERIAL = PERSON.SERIAL
        AND ACCT.CLOSE_DATE IS NULL
        AND NOTE_TYPE.DESCRIPTION LIKE '%Deceased Member%'
        AND (AC_NOTE.EXPIRATION_DATE IS NULL OR AC_NOTE.EXPIRATION_DATE > ENV.POSTING_DATE)
  )
